/**
 * Generates src/generated/s700.ts — the game logic of the pinned S700 decompilation translated
 * to TypeScript by tools/j2ts/J2TS.java — after applying the shared harness patches. The output is
 * not versioned: like the extracted assets, it is rebuilt from the reference clone.
 * Requires a JDK 21 (javac/java on PATH, or DIAMOND_JDK_BIN): J2TS uses javac tree classes that JDK 17 lacks.
 * Usage: node tools/generate-core.ts [reference-dir]
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { patchReferenceSources } from './routes/ReferencePatches.ts';
import { readReferenceSources } from './routes/JavaOracle.ts';

const repo=fileURLToPath(new URL('../',import.meta.url));
const reference=resolve(process.argv[2]??process.env.DIAMOND_REFERENCE??join(repo,'../../work/reference-s700'));
const jdkBin=process.env.DIAMOND_JDK_BIN??'';
const exe=(name:string)=>jdkBin?join(jdkBin,process.platform==='win32'?`${name}.exe`:name):name;
const work=join(tmpdir(),`diamond-rush-core-${process.pid}`);
const src=join(work,'src'),stubs=join(work,'stubs'),tool=join(work,'j2ts'),out=join(work,'ts');
for(const dir of [src,stubs,tool,out])mkdirSync(dir,{recursive:true});
function run(file:string,args:string[]){
  const result=spawnSync(file,args,{encoding:'utf8',maxBuffer:64*1024*1024});
  if(result.error)throw new Error(`${file}: ${result.error.message}. Install a JDK 21 or set DIAMOND_JDK_BIN.`);
  if(result.status)throw new Error(`${file} failed:\n${result.stderr}${result.stdout}`);
  return result.stdout;
}
function javaFiles(dir:string):string[]{
  return readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?javaFiles(join(dir,e.name)):e.name.endsWith('.java')?[join(dir,e.name)]:[]);
}
try{
  const {files,log}=patchReferenceSources(readReferenceSources(reference),'ts');
  for(const [name,text] of files)writeFileSync(join(src,name),text,'latin1');
  copyFileSync(join(repo,'tools/oracle/DeviceClock.java'),join(src,'DeviceClock.java'));
  // J2TS attributes the sources with javac; the J2ME stubs provide the platform types.
  run(exe('javac'),['-nowarn','-d',stubs,...javaFiles(join(repo,'tools/oracle/stubs'))]);
  const exports=['tree','code','util'].map(p=>`--add-exports=jdk.compiler/com.sun.tools.javac.${p}=ALL-UNNAMED`);
  run(exe('javac'),[...exports,'-nowarn','-d',tool,join(repo,'tools/j2ts/J2TS.java')]);
  run(exe('java'),[...exports,'-cp',tool,'J2TS',out,stubs,...readdirSync(src).map(n=>join(src,n))]);
  // Class bodies run static initializers in this order; cGame needs the others defined first.
  const order=['DeviceClock','Define','Utils','ASprite','ASpriteInstance','DemoInterpreter','GemsRain','IGA','cSoundEngine','cGame','GloftDIRU'];
  const produced=readdirSync(out).map(n=>n.replace(/\.ts$/,''));
  const missing=produced.filter(n=>!order.includes(n));
  if(missing.length)throw new Error(`Unordered generated classes: ${missing.join(', ')}`);
  const hash=createHash('sha256');for(const name of [...files.keys()].sort())hash.update(name).update(files.get(name)!);
  const sourceHash=hash.digest('hex');
  let text=`// GENERATED by tools/generate-core.ts from the pinned S700 decompilation (${sourceHash.slice(0,12)}).\n`+
    `// Do not edit or commit. Patches: ${log.join('; ')}.\n// @ts-nocheck\n`+
    `import * as J from '../core/s700/runtime.ts';\n`+
    `import { Graphics, Image, Font, Canvas, GameCanvas, Display, Sprite, MIDlet, RecordStore, Manager } from '../core/s700/j2me.ts';\n`+
    `export const S700_SOURCE_SHA256 = '${sourceHash}';\n`;
  for(const name of order)if(produced.includes(name))text+=readFileSync(join(out,`${name}.ts`),'utf8').replace(/^\/\/ Generated from .*\n/,'')+'\n';
  mkdirSync(join(repo,'src/generated'),{recursive:true});
  writeFileSync(join(repo,'src/generated/s700.ts'),text);
  console.log(`Generated src/generated/s700.ts (${Math.round(text.length/1024)} KiB) from ${reference}; source ${sourceHash.slice(0,12)}.`);
}finally{rmSync(work,{recursive:true,force:true});}
